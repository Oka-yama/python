# Solicite que o usuário insira dois números e faça
# a soma (+), a multiplicação (*), a divisão (/) e
# a subtração (-) dos números inseridos

num1 = int(input("Digite o primeiro número "))
num2 = int(input("Digite o segundo número: "))

soma = num1 + num2
sub = num1 - num2
multi = num1 * num2
div = num1 / num2

print("Soma:", soma)
print("Sub:", sub)
print("Multi:", multi)
print("Div:", div)